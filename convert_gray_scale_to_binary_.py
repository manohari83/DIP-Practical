import os
from PIL import Image
import numpy as np
import matplotlib.pyplot as plt

# Create a dummy image if image.jpg doesn't exist
if not os.path.exists('image1.jpg'):
    print("'image1.jpg' not found. Creating a placeholder image...")
    # Create a 200x200 gradient image
    placeholder = np.fromfunction(lambda x, y: (x + y) * 255 / 400, (200, 200)).astype(np.uint8)
    Image.fromarray(placeholder).save('image1.jpg')

# Load the grayscale image
img = Image.open('image1.jpg').convert('L')

# Convert image into NumPy array
gray = np.array(img)

# Set threshold value
threshold = 127

# Convert grayscale image to binary
binary = np.where(gray > threshold, 255, 0)

# Display grayscale and binary images
plt.subplot(1, 2, 1)
plt.imshow(gray, cmap='gray')
plt.title('Grayscale Image')
plt.axis('off')

plt.subplot(1, 2, 2)
plt.imshow(binary, cmap='gray')
plt.title('Binary Image')
plt.axis('off')

plt.show()

# Save binary image
Image.fromarray(binary.astype(np.uint8)).save('binary_image.png')